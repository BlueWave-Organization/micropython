class MiniOLED(framebuf.FrameBuffer):
    def __init__(self, width, height, i2c, addr=0x3C):
        self.i2c = i2c
        self.addr = addr
        self.width = width
        self.height = height
        self.pages = self.height // 8
        self.buffer = bytearray(self.pages * self.width)
        
        # بافرهای ارسال داده از کلاس فرزند
        self.temp = bytearray(2)
        self.write_list = [b"\x40", None]

        super().__init__(self.buffer, self.width, self.height, framebuf.MONO_VLSB)
        self.init_display()

    def write_cmd(self, cmd):
        self.temp[0] = 0x80
        self.temp[1] = cmd
        self.i2c.writeto(self.addr, self.temp)

    def write_data(self, buf):
        self.write_list[1] = buf
        self.i2c.writevto(self.addr, self.write_list)

    def init_display(self):
        for cmd in (
            0xAE,        # off
            0x20, 0x00,  # horizontal addressing
            0x40,        # start line
            0xA1,        # segment remap
            0xA8, self.height - 1, # mux ratio
            0xC8,        # com out dir
            0xD3, 0x00,  # display offset
            0xDA, 0x02 if self.width > 2 * self.height else 0x12, # com pin cfg
            0xD5, 0x80,  # clock div
            0xD9, 0xF1,  # precharge
            0xDB, 0x30,  # vcom deselect
            0x81, 0xFF,  # contrast (max)
            0xA4,        # entire on
            0xA6,        # normal (not inverted)
            0x8D, 0x14,  # charge pump
            0xAF         # on
        ):
            self.write_cmd(cmd)
        self.fill(0)
        self.show()

    def show(self):
        x0 = 0
        x1 = self.width - 1
        if self.width == 64:
            x0 += 32
            x1 += 32
        
        for cmd in (0x21, x0, x1, 0x22, 0, self.pages - 1):
            self.write_cmd(cmd)
            
        self.write_data(self.buffer)


